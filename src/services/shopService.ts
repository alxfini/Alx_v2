export function formatPriceFromStore(rawPrice: string | number, minorUnits: number = 2): string {
  if (rawPrice === null || rawPrice === undefined) return '';
  const str = String(rawPrice).trim();
  if (str === '0' || str === '' || str.toLowerCase() === 'grátis' || str.toLowerCase() === 'gratis') return 'Doação Livre';
  if (str.includes('R$')) return str;

  // Se já vier com vírgula ou ponto decimal explícito (ex: "149.00" ou "149,00")
  if (str.includes(',') || (str.includes('.') && str.indexOf('.') === str.length - 3)) {
    const normalized = str.replace(',', '.');
    const num = parseFloat(normalized);
    if (!isNaN(num)) {
      return num.toLocaleString('pt-BR', { style: 'currency', currency: 'BRL' });
    }
  }

  // Preço em centavos (inteiro da API WooCommerce Store)
  const num = parseInt(str, 10);
  if (!isNaN(num)) {
    const divisor = Math.pow(10, minorUnits > 0 ? minorUnits : 2);
    const actualVal = num / divisor;
    return actualVal.toLocaleString('pt-BR', { style: 'currency', currency: 'BRL' });
  }

  return str;
}

export function calculateDiscount(reg: string | number, sale: string | number): string | undefined {
  const r = typeof reg === 'string' ? parseFloat(reg) : reg;
  const s = typeof sale === 'string' ? parseFloat(sale) : sale;
  if (!r || !s || r <= s) return undefined;
  const pct = Math.round(((r - s) / r) * 100);
  return `${pct}% OFF`;
}

/**
 * Fetch and synchronize products from the live ALX Shop WooCommerce instance
 */
export async function syncShopProductsFromStore(
  customUrl?: string,
  existingProducts?: ProductItem[]
): Promise<{ success: boolean; count: number; products?: ProductItem[]; error?: string }> {
  try {
    const targetUrl = 'https://alxshop.7f.com.br/wp-json/wc/store/v1/products?per_page=100';
    
    // Lista de endpoints em ordem de preferência
    // 1. /api/shop.php (Proxy oficial no servidor Hostinger sem bloqueio CORS)
    // 2. /api/wc-shop (Proxy Vite local em ambiente de desenvolvimento)
    // 3. Chamada direta ao endpoint WooCommerce Store
    // 4. Proxy AllOrigins como fallback
    const endpointsToTry: string[] = [
      '/api/shop.php?refresh=1',
      '/api/shop.php',
      '/api/wc-shop/wp-json/wc/store/v1/products?per_page=100',
      targetUrl,
      `https://api.allorigins.win/raw?url=${encodeURIComponent(targetUrl)}`
    ];

    if (customUrl && customUrl.includes('/wp-json/')) {
      endpointsToTry.unshift(customUrl);
    }

    let rawData: any[] | null = null;
    let usedEndpoint = '';

    for (const endpoint of endpointsToTry) {
      try {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 6000);

        const res = await fetch(endpoint, {
          signal: controller.signal,
          headers: {
            'Accept': 'application/json'
          }
        });
        clearTimeout(timeoutId);

        if (res.ok) {
          const contentType = res.headers.get('content-type') || '';
          if (contentType.includes('application/json')) {
            const json = await res.json();
            if (Array.isArray(json) && json.length > 0) {
              rawData = json;
              usedEndpoint = endpoint;
              break;
            }
          }
        }
      } catch {
        // Tenta o próximo endpoint
      }
    }

    if (!rawData || rawData.length === 0) {
      // Se já temos produtos válidos no estado atual, mantemos sem sobrescrever com dados desatualizados
      if (existingProducts && existingProducts.length > 0) {
        return {
          success: true,
          count: existingProducts.length,
          products: existingProducts
        };
      }
      return {
        success: true,
        count: initialShopProducts.length,
        products: initialShopProducts
      };
    }

    const baseCatalog = (existingProducts && existingProducts.length > 0) ? existingProducts : initialShopProducts;

    const parsedProducts: ProductItem[] = rawData.map((item: any, index: number) => {
      // Procura item de referência para preservar descrições ou metadados
      const fallbackItem = baseCatalog.find(
        (p) => p.slug === item.slug || p.id === `shop-${item.id}` || p.name.toLowerCase().trim() === (item.name || '').toLowerCase().trim()
      ) || initialShopProducts.find(
        (p) => p.slug === item.slug || p.id === `shop-${item.id}` || p.name.toLowerCase().trim() === (item.name || '').toLowerCase().trim()
      );

      // 1. Resposta nativa da API WooCommerce Store (wc/store/v1)
      if (item.prices) {
        const minorUnit = typeof item.prices.currency_minor_unit === 'number' ? item.prices.currency_minor_unit : 2;
        const rawCurrentPrice = item.prices.price || item.prices.sale_price || item.prices.regular_price;
        const rawRegularPrice = item.prices.regular_price;
        
        const numCurrent = typeof rawCurrentPrice === 'string' ? parseFloat(rawCurrentPrice) : Number(rawCurrentPrice);
        const numRegular = typeof rawRegularPrice === 'string' ? parseFloat(rawRegularPrice) : Number(rawRegularPrice);
        const isDiscounted = numRegular > 0 && numCurrent > 0 && numRegular > numCurrent;
        
        let priceStr = formatPriceFromStore(rawCurrentPrice, minorUnit);
        if (!priceStr || priceStr.toLowerCase().includes('consulta') || priceStr === 'R$ 0,00') {
          if (rawCurrentPrice === '0' || rawCurrentPrice === 0) {
            priceStr = 'Doação Livre';
          } else if (fallbackItem?.price) {
            priceStr = fallbackItem.price;
          }
        }

        const originalPriceStr = isDiscounted ? formatPriceFromStore(rawRegularPrice, minorUnit) : fallbackItem?.originalPrice;
        const discountBadge = isDiscounted ? calculateDiscount(rawRegularPrice, rawCurrentPrice) : fallbackItem?.badge;

        const mainImage = item.images?.[0]?.src || fallbackItem?.imageUrl || '/imagens/produtos/dongle-v2.jpg';
        const allImages = (item.images && item.images.length > 0) 
          ? item.images.map((img: any) => img.src) 
          : (fallbackItem?.images || [mainImage]);
          
        const categoryName = item.categories?.[0]?.name || fallbackItem?.category || 'Geral';
        const cleanDesc = (item.short_description || item.description || fallbackItem?.description || '')
          .replace(/<[^>]*>?/gm, '')
          .replace(/&nbsp;/g, ' ')
          .replace(/&#8211;/g, '–')
          .trim();

        return {
          id: `shop-${item.id || index}`,
          name: (item.name || fallbackItem?.name || '').replace(/&#8211;/g, '–').replace(/&amp;/g, '&'),
          slug: item.slug || fallbackItem?.slug || `produto-${item.id}`,
          category: categoryName,
          description: cleanDesc.slice(0, 140) + (cleanDesc.length > 140 ? '...' : ''),
          fullDescription: cleanDesc || item.name,
          price: priceStr,
          originalPrice: originalPriceStr,
          imageUrl: mainImage,
          images: allImages,
          buyUrl: item.permalink || fallbackItem?.buyUrl || `https://alxshop.7f.com.br/?p=${item.id}`,
          badge: discountBadge || (index === 0 ? 'Destaque' : fallbackItem?.badge),
          inStock: item.is_in_stock !== false,
          featured: fallbackItem?.featured ?? (index < 2),
          rating: fallbackItem?.rating ?? (4.8 + ((index % 3) * 0.1)),
          specs: fallbackItem?.specs || [
            { label: 'Origem', value: 'Loja Oficial ALX Shop' },
            { label: 'Disponibilidade', value: 'Em Estoque' },
            { label: 'Garantia', value: 'Garantia & Suporte ALX' }
          ]
        };
      }

      // 2. Se já vier como produto normalizado (ex: retornado de cache ou site-data.json)
      if (item.price && typeof item.price === 'string') {
        return {
          id: item.id || `shop-${index}`,
          name: item.name || fallbackItem?.name || 'Produto',
          slug: item.slug || fallbackItem?.slug || `produto-${index}`,
          category: item.category || fallbackItem?.category || 'Geral',
          description: item.description || fallbackItem?.description || '',
          fullDescription: item.fullDescription || item.description || '',
          price: item.price,
          originalPrice: item.originalPrice || fallbackItem?.originalPrice,
          imageUrl: item.imageUrl || fallbackItem?.imageUrl || '',
          images: item.images || fallbackItem?.images || [],
          buyUrl: item.buyUrl || fallbackItem?.buyUrl || 'https://alxshop.7f.com.br/',
          badge: item.badge || fallbackItem?.badge,
          inStock: item.inStock !== false,
          featured: item.featured ?? fallbackItem?.featured,
          rating: item.rating || fallbackItem?.rating || 5.0,
          specs: item.specs || fallbackItem?.specs
        };
      }

      // 3. Fallback genérico mantendo preço do catálogo
      const title = item.title?.rendered ? item.title.rendered.replace(/&#8211;/g, '–').replace(/&amp;/g, '&') : (fallbackItem?.name || `Produto ${item.id}`);
      const mainImage = item._embedded?.['wp:featuredmedia']?.[0]?.source_url || fallbackItem?.imageUrl || '/imagens/produtos/dongle-v2.jpg';
      const cleanDesc = (item.content?.rendered || item.excerpt?.rendered || fallbackItem?.description || '')
        .replace(/<[^>]*>?/gm, '')
        .trim();

      return {
        id: `shop-${item.id || index}`,
        name: title,
        slug: item.slug || fallbackItem?.slug || `produto-${item.id}`,
        category: fallbackItem?.category || 'Geral',
        description: cleanDesc.slice(0, 140) + (cleanDesc.length > 140 ? '...' : ''),
        fullDescription: cleanDesc || title,
        price: fallbackItem?.price || 'R$ 149,00',
        originalPrice: fallbackItem?.originalPrice,
        imageUrl: mainImage,
        images: fallbackItem?.images || [mainImage],
        buyUrl: item.link || fallbackItem?.buyUrl || `https://alxshop.7f.com.br/?p=${item.id}`,
        badge: fallbackItem?.badge,
        inStock: true,
        rating: fallbackItem?.rating || 5.0,
        specs: fallbackItem?.specs || [
          { label: 'Origem', value: 'Loja Oficial ALX Shop' }
        ]
      };
    });

    return {
      success: true,
      count: parsedProducts.length,
      products: parsedProducts
    };
  } catch (error: any) {
    console.error('Error syncing products from store:', error);
    return {
      success: false,
      count: 0,
      error: error?.message || 'Falha ao sincronizar produtos da loja'
    };
  }
}
